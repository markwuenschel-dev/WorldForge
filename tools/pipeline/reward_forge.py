#!/usr/bin/env python3
"""reward_forge.py — WorldForge v1.9 deterministic reward/progression dataset spine.

One source of truth for the whole v1.9 authoring dataset so every generator,
validator, and (Wave R) the runtime bridge draw the SAME equipment catalog,
unlock catalog, reward tables, and grant/state derivation. Everything here is
deterministic: fixed timestamps, ids-derived ordering, no wall-clock / RNG — the
same inputs always produce byte-identical records, which is what lets the
determinism and report-integrity gates hold.

Layers:
  * EQUIPMENT_CATALOG / build_equipment_catalog()  — bounded EquipmentItem set
  * UNLOCK_CATALOG / build_unlock_catalog()         — unlock DEFINITIONS
  * build_loadout_profiles()                        — a few LoadoutProfiles
  * build_reward_tables()                           — one table per archetype×risk
  * simulate_grant(table, ...)                      — deterministic grant -> event
  * derive_states(grants)                           — Inventory/Progression/Unlock
  * save_load_roundtrip(state, kind)                — model-level persistence proof
  * classify_risk_reward(...)                       — risk/reward classification

The grant simulation and state derivation here are the AUTHORING-side model:
they produce contract-valid evidence marked ``created_at="authoring"`` so the
Wave-2 validators have real data to gate. The Wave-R runtime bridge produces the
``created_at="live"`` runtime evidence the ``--require-live`` shield lane needs;
both share this module's derivation so authoring and runtime can never disagree
about what a given reward SHOULD do to state.
"""
