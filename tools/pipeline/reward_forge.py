def build_reward_tables():
    """Deterministic reward tables: 6 archetypes × 2 risk bands = 12 tables."""
    tables = []
    biomes = RX.KNOWN_BIOMES
    for ai, archetype in enumerate(RX.MISSION_ARCHETYPES):
        biome = biomes[ai % len(biomes)]
        cp_id = COMBAT_PROFILE_IDS[ai % len(COMBAT_PROFILE_IDS)]
        for risk, tier in _RISK_TIERS.items():
            entries = [
                {"reward_entry_id": "re_{}_{}_xp".format(archetype, risk), "reward_type": "xp",
                 "item_id": None, "xp_amount": tier["xp"], "unlock_id": None, "currency_amount": 0.0,
                 "weight": 2.0, "min_mission_result": "completed", "max_repeat_count": 5, "grant_once": False},
                {"reward_entry_id": "re_{}_{}_item".format(archetype, risk), "reward_type": "item",
                 "item_id": tier["item"], "xp_amount": 0.0, "unlock_id": None, "currency_amount": 0.0,
                 "weight": 1.0, "min_mission_result": "completed", "max_repeat_count": 1, "grant_once": True},
            ]
            if tier["adds_unlock"]:
                # Distinct unlock per mission archetype (1:1), so no unlock is ever
                # re-granted across the authoring chain.
                unlock_id = UNLOCK_IDS[ai % len(UNLOCK_IDS)]
                entries.append(
                    {"reward_entry_id": "re_{}_{}_unlock".format(archetype, risk), "reward_type": "unlock",
                     "item_id": None, "xp_amount": 0.0, "unlock_id": unlock_id, "currency_amount": 0.0,
                     "weight": 1.0, "min_mission_result": "completed", "max_repeat_count": 1, "grant_once": True})
            table = {
                "reward_table_id": _table_id(archetype, risk), "pack_id": PACK,
                "mission_archetype": archetype, "biome": biome, "combat_profile_id": cp_id,
                "risk_band": risk, "reward_entries": entries, "budget_min": tier["bmin"],
                "budget_max": tier["bmax"],
                "anti_exploit_rules": ["grant_once_stable", "budget_capped", "min_result_completed"],
                "seed": ai, "created_by": CREATED_BY, "created_at": CREATED_AT_AUTHORING,
                "schema_version": RX.REWARD_TABLE_SCHEMA_VERSION, "report_type": RX.RT_REWARD_TABLE,
            }
            tables.append(table)
    return tables


